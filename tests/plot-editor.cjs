// Run against pnpm preview. Optional PLAYWRIGHT_MODULE and REPORT_DRAWER_URL.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')

async function main() {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' })
  try {
    const context = await browser.newContext({ viewport: { width: 1366, height: 980 }, acceptDownloads: true })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.goto(process.env.REPORT_DRAWER_URL || 'http://127.0.0.1:4173')
    await page.getByRole('button', { name: '新建报告', exact: true }).click()
    const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('report-drawer:reports:v1'))[0])
    const modal = page.getByRole('dialog', { name: 'XY 波形绘制器' })
    const button = name => modal.getByRole('button', { name, exact: true })
    const field = text => modal.getByLabel(text, { exact: true })
    const chartFields = ['图表标题', 'X 最大值', 'X 最小值', 'Y 最大值', 'Y 最小值']
    const tab = name => modal.getByRole('tab', { name, exact: true }).click()
    async function set(text, value) {
      await tab(chartFields.includes(text) ? '图表' : '曲线')
      if (['相移 s（X 单位）', '偏移 b'].includes(text)) await modal.locator('.more-parameters').evaluate(el => { el.open = true })
      await field(text).fill(String(value)); await field(text).press('Tab')
    }
    await page.getByRole('button', { name: '插入 XY 图表', exact: true }).click()
    await modal.waitFor()
    assert.equal(await modal.locator('input:visible').count(), 4, 'default inspector shows only four waveform parameters')
    assert.equal(await field('高电平').inputValue(), '1')
    assert.equal(await field('低电平').inputValue(), '-1')
    // Real mouse dragging: high level, duty and one gesture = one undo.
    async function drag(selector, dx, dy) {
      const box = await modal.locator(selector).boundingBox()
      assert.ok(box)
      await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
      await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + dx, box.y + box.height / 2 + dy, { steps: 8 }); await page.mouse.up()
    }
    await drag('[data-handle="high"] circle:last-of-type', 0, 20)
    assert.ok(Number(await field('高电平').inputValue()) < 1)
    await button('撤销').click()
    assert.equal(await field('高电平').inputValue(), '1')
    await drag('[data-handle="duty"] circle:last-of-type', 30, 0)
    assert.ok(Number(await field('占空比（0—1）').inputValue()) > 0.5)
    await page.keyboard.press('Control+z')
    assert.equal(await field('占空比（0—1）').inputValue(), '0.5')
    await set('周期 T', 2.5); await set('相移 s（X 单位）', -0.25); await set('占空比（0—1）', 0.2)
    await set('图表标题', '实验波形：+1 / −1')
    await field('用竖线标记跳变').uncheck()
    await tab('曲线')
    await modal.locator('.curve-appearance summary').click()
    await button('复制为节点曲线').click()
    await field('当前节点').selectOption('1')
    assert.equal(await field('X').inputValue(), '0.25')
    assert.equal(await field('Y').inputValue(), '-1')
    await drag('[data-handle="node"][data-index="1"] circle:last-of-type', 12, 10)
    const movedX = Number(await field('X').inputValue())
    assert.ok(movedX > 0.25)
    await button('撤销').click()
    assert.equal(await field('X').inputValue(), '0.25')
    await field('到下一节点').selectOption('break')
    await modal.locator('.node-data summary').click()
    await field('节点数据').fill('0\t1\thold\n1\t-1\thold\n2\t1\tline\n3\t0\tbreak\n4\t0.5')
    await button('应用数据').click()
    await field('节点数据').fill('0\t1\n-1\t0')
    await button('应用数据').click()
    assert.ok((await modal.getByRole('alert').textContent()).includes('第 2 行'))
    await button('读取当前节点').click()
    await modal.locator('.node-data summary').click()
    await button('添加曲线').click(); await modal.locator('.template-picker').getByRole('button', { name: '正弦', exact: true }).click()
    await set('周期 T', 3)
    await modal.locator('.plot-body, .plot-main, .inspector-content').evaluateAll(elements => elements.forEach(el => { el.scrollTop = 0 }))
    await modal.screenshot({ path: 'tmp/plot-editor-desktop.png' })
    await page.setViewportSize({ width: 390, height: 844 })
    await modal.screenshot({ path: 'tmp/plot-editor-mobile.png' })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    const overflow = await modal.evaluate(el => Array.from(el.querySelectorAll('input, select, button')).filter(n => { const r = n.getBoundingClientRect(), box = el.getBoundingClientRect(); return r.width && (r.left < box.left - 1 || r.right > box.right + 1) }).length)
    assert.equal(overflow, 0)
    for (const width of [320, 800, 1000]) {
      await page.setViewportSize({ width, height: 844 })
      assert.equal(await modal.evaluate(el => Array.from(el.querySelectorAll('button, input, select')).filter(n => {
        if (!n.checkVisibility()) return false
        const r = n.getBoundingClientRect(), box = el.getBoundingClientRect()
        return r.left < box.left - 1 || r.right > box.right + 1
      }).length), 0, `controls stay within the dialog at ${width}px`)
    }
    await page.setViewportSize({ width: 1366, height: 980 })
    // Custom cycle: unequal sections and endpoint values remain independent.
    await button('添加曲线').click(); await button('自定义周期').click()
    await field('当前节点').selectOption('2')
    const beforeX = Number(await field('X').inputValue())
    await drag('[data-handle="node"][data-index="2"] circle:last-of-type', 40, 12)
    assert.ok(Number(await field('X').inputValue()) > beforeX)
    await field('当前节点').selectOption('1')
    assert.equal(await field('Y').inputValue(), '1', 'other side is not mirrored')
    await field('当前节点').selectOption('0')
    assert.equal(await field('X').isDisabled(), true)
    await set('Y', 0.4)
    await field('当前节点').selectOption('4')
    assert.equal(await field('Y').inputValue(), '0.6', 'cycle endpoints may differ')
    await set('周期 T', 2.5)
    assert.equal(await field('X').inputValue(), '2.5')
    await set('相移 s（X 单位）', 0.25)
    await modal.locator('.more-parameters summary').click()
    await button('重复预览').click()
    assert.equal(await modal.locator('[data-handle="node"]').count(), 0)
    await modal.screenshot({ path: 'tmp/plot-custom-cycle.png' })
    await button('编辑一个周期').click()
    await modal.screenshot({ path: 'tmp/plot-cycle-edit.png' })
    await field('图表插入页').selectOption('2')
    await button('插入报告').click()
    const first = (await stored()).images[0]
    assert.equal(first.page, 2); assert.equal(first.plot.curves.length, 4)
    assert.equal(first.plot.curves[3].repeat, true)
    assert.equal(first.plot.curves[3].nodes[0].y, 0.4)
    assert.equal(first.plot.curves[3].nodes[4].y, 0.6)
    assert.equal(first.plot.curves[1].nodes[1].next, 'hold')
    assert.equal(first.plot.curves[1].nodes[3].next, 'break')
    assert.ok(first.src.startsWith('data:image/svg+xml'))
    const image = page.locator('.image-overlay').first()
    await image.scrollIntoViewIfNeeded(); await image.dblclick()
    await set('图表标题', '改动后取消')
    await button('取消').click()
    assert.equal((await stored()).images[0].plot.title, first.plot.title)
    await image.dblclick(); await set('图表标题', '已保存的波形'); await button('保存图表').click()
    assert.equal((await stored()).images[0].plot.title, '已保存的波形')
    await page.getByTitle('撤销 (Ctrl+Z)', { exact: true }).click()
    assert.equal((await stored()).images[0].plot.title, first.plot.title)
    await page.getByTitle('重做 (Ctrl+Y)', { exact: true }).click()
    assert.equal((await stored()).images[0].plot.title, '已保存的波形')
    await page.reload()
    assert.equal((await stored()).images[0].plot.curves[3].repeat, true)
    assert.equal((await stored()).images[0].plot.curves[3].nodes[0].y, 0.4)
    assert.equal((await stored()).images[0].plot.curves[3].nodes[4].y, 0.6)
    await page.locator('.image-overlay').dblclick()
    await tab('图表')
    assert.equal(await field('图表标题').inputValue(), '已保存的波形')
    await field('X 最大值').fill('0'); await field('X 最大值').press('Tab')
    assert.equal(await button('保存图表').isDisabled(), true)
    await button('撤销').click()
    assert.equal(await button('保存图表').isEnabled(), true)
    await button('取消').click()
    // The SVG saved with the plot is independently decodable and contains visible curve pixels.
    const decoded = await page.locator('.image-overlay img').evaluate(async img => {
      await img.decode()
      const c = document.createElement('canvas'); c.width = 800; c.height = 500
      const ctx = c.getContext('2d'); ctx.drawImage(img, 0, 0)
      const bytes = ctx.getImageData(0, 0, 800, 500).data
      let blue = 0; for (let i = 0; i < bytes.length; i += 4) if (bytes[i + 2] > 150 && bytes[i] < 100 && bytes[i + 1] < 180) blue++
      return blue
    })
    assert.ok(decoded > 500)
    await page.locator('.image-overlay').screenshot({ path: 'tmp/plot-report.png' })
    await page.getByLabel('导出格式').selectOption('pdf')
    const pdfDownload = page.waitForEvent('download', { timeout: 60000 })
    await page.getByRole('button', { name: '导出 PDF', exact: true }).click()
    const pdf = await pdfDownload
    await pdf.saveAs('tmp/plot-report.pdf')
    assert.equal(fs.readFileSync('tmp/plot-report.pdf').subarray(0, 5).toString(), '%PDF-')
    await page.getByText('导出完成 ✓', { exact: true }).waitFor()
    await page.getByLabel('导出格式').selectOption('png')
    const downloads = []
    page.on('download', download => downloads.push(download))
    await page.getByRole('button', { name: '导出图片', exact: true }).click()
    await page.getByText('导出完成 ✓', { exact: true }).waitFor()
    await page.waitForFunction(() => document.querySelector('.status')?.textContent === '导出完成 ✓')
    // Downloads are emitted as the two pages are rendered; wait for the second event if necessary.
    if (downloads.length < 2) await page.waitForEvent('download', { timeout: 15000 })
    assert.equal(downloads.length, 2)
    for (let i = 0; i < 2; i++) await downloads[i].saveAs(`tmp/plot-page-${i + 1}.png`)
    assert.deepEqual(errors, [])
    console.log('PASS: compact inspector, tabs, template/node dragging, custom asymmetric cycle, independent endpoints, period rescale, repetition preview, gesture undo, mixed segments, data paste, narrow layout, page 2 insert, save/cancel, report undo/redo, reload, SVG decode, PDF and both PNG downloads')
  } finally { await browser.close() }
}
main().catch(e => { console.error(e); process.exitCode = 1 })
